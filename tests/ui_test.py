import json, sys
from playwright.sync_api import sync_playwright
ORACLE = json.load(open('/home/claude/mock4/tests/blind_oracle.json'))
errs=[]; res=[]
def check(n,c,i=''): res.append((n,bool(c))); print(('PASS ' if c else 'FAIL ')+n+('' if c else '  '+str(i)))
with sync_playwright() as p:
    b=p.chromium.launch(executable_path='/usr/bin/google-chrome',args=['--no-sandbox'])
    pg=b.new_page(viewport={'width':1600,'height':1000})
    pg.on('console',lambda m:m.type=='error' and errs.append(m.text)); pg.on('pageerror',lambda e:errs.append(str(e)))
    pg.goto('file:///home/claude/mock4/app/index.html'); pg.wait_for_timeout(300)
    pg.click('#runBtn'); pg.wait_for_function("document.querySelector('#status').textContent.startsWith('Done')",timeout=20000)
    check('demo run renders 3 emails', pg.locator('.mail').count()==3)
    check('task cards render', pg.locator('.task').count()>=1)
    check('gates shown for D1 certificate', pg.locator('.gsum span').count()>=5)
    check('trace spans render', pg.locator('.sp').count()>10)
    check('conservation bar green', 'valid end state' in pg.inner_text('#cons') and '✓' in pg.inner_text('#cons'))
    pg.screenshot(path='/home/claude/mock4/tests/ui_demo.png')
    pg.click('[data-ap="D1-T1"]'); pg.wait_for_timeout(150)
    check('approve -> Sent', 'Sent' in pg.inner_text('#tasks') or 'sent once' in pg.inner_text('#tasks'))
    pg.click('[data-ap="D1-T1"]'); pg.wait_for_timeout(150)
    check('second approve: one record_send span only', pg.evaluate("window.__mas.state.R.T.spans.filter(s=>s.attributes['gen_ai.tool.name']==='record_send').length")==1)
    pg.locator('.mail').nth(1).click(); pg.wait_for_timeout(100)
    check('D2 shows 2 tasks', pg.locator('.task').count()==2)
    pg.locator('.task .thead').first.click(); pg.wait_for_timeout(100)
    check('task filter on trace', 'showing' in pg.inner_text('#trace'))
    pg.locator('#trace .sp').filter(has_text='invoke_agent fulfillment').first.click(); pg.wait_for_timeout(100)
    check('span detail shows input and output', 'input' in pg.inner_text('#trace .detail').lower() and 'output' in pg.inner_text('#trace .detail').lower() and 'ROLE:' in pg.inner_text('#trace .detail'))
    check('scores on trace', pg.locator('#trace .score').count()>=1)
    pg.locator('#trace').screenshot(path='/home/claude/mock4/tests/ui_trace_detail.png')
    pg.evaluate("document.querySelector('details.adv').open=true"); pg.click('#killBtn'); check('kill switch banner', pg.is_visible('#killBanner')); pg.wait_for_timeout(50); pg.evaluate("document.querySelector('details.adv').open=true"); pg.click('#killBtn'); pg.evaluate("document.querySelector('details.adv').open=false")
    # blind via saved oracle (offline stand-in for live)
    pg.click('#dsBlind'); pg.evaluate("o=>{window.__mas.setSaved('blind',o)}", ORACLE); pg.wait_for_timeout(100)
    pg.evaluate("()=>{const M=window.__mas;M.state.mode='saved';document.querySelector('#runBtn').disabled=false}")
    pg.click('#runBtn'); pg.wait_for_function("document.querySelector('#status').textContent.startsWith('Done')",timeout=20000)
    ev=pg.inner_text('#evalBody'); check('eval scorecard 8/8', '8/8' in ev, ev[:300])
    check('dup tag on B2', 'Duplicate of B1' in pg.inner_text('#inbox'))
    check('injection tag on B1', 'Instruction in text ignored' in pg.inner_text('#inbox'))
    pg.screenshot(path='/home/claude/mock4/tests/ui_blind.png', full_page=False)
    check('story panel on B1', 'escalated first' in pg.inner_text('#tasks') and 'blocked by code' in pg.inner_text('#tasks'), pg.inner_text('#tasks')[:400])
    pg.click('#vTime'); pg.wait_for_timeout(100); check('timeline svg renders', pg.locator('#trace svg.tl rect').count()>15)
    pg.locator('#trace').screenshot(path='/home/claude/mock4/tests/ui_timeline.png'); pg.click('#vTree')
    pg.click('#layFe'); check('frontend view hides the trace', not pg.is_visible('#trace') and pg.is_visible('#tasks'))
    pg.click('#layBe'); check('backend view hides the advisor console', pg.is_visible('#trace') and not pg.is_visible('#tasks'))
    pg.click('#layBoth'); check('eval shows expected vs actual', 'Expected (ground truth, frozen)' in pg.inner_text('#evalBody'))
    check('ground truth box lists frozen outcome and records', 'GL-RWL-2026' in pg.evaluate("document.querySelector('#gtBody').textContent") and 'Raw frozen file' in pg.evaluate("document.querySelector('#gtBody').textContent"))
    pg.evaluate("document.querySelector('details.adv').open=true"); pg.click('#tourBtn'); n=0
    while pg.is_visible('#tour') and n<12:
        n+=1; pg.screenshot(path=f'/home/claude/mock4/tests/ui_tour_{n}.png'); pg.click('#tNext'); pg.wait_for_timeout(250)
    check('blind walkthrough runs 7 steps and closes', n==7, n)
    pg.locator('.mail').nth(1).click(); check('story on duplicate', 'Resend of B1' in pg.inner_text('#tasks'))
    pg.locator('#archBox').evaluate('d=>d.open=true'); pg.locator('#archBox').scroll_into_view_if_needed()
    check('architecture svg present', pg.locator('#archBody svg').count()==3)
    pg.locator('#archBody').screenshot(path='/home/claude/mock4/tests/ui_arch.png')
    pg.locator('#evalBox').screenshot(path='/home/claude/mock4/tests/ui_eval.png')
    b.close()
check('no console errors', not errs, errs)
json.dump([{'test':n,'pass':p} for n,p in res], open('/home/claude/mock4/tests/ui_results.json','w'), indent=1)
f=[r for r in res if not r[1]]; print(f'{len(res)-len(f)}/{len(res)} passed'); sys.exit(1 if f else 0)
